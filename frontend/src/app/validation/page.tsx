"use client";

import React, { useState, useEffect } from "react";
import Link from "next/link";
import { ArrowLeft, Check, X, AlertCircle } from "lucide-react";
import { Header } from "../../components/Header";
import { Footer } from "../../components/Footer";
import { AssumptionsDrawer } from "../../components/AssumptionsDrawer";
import { DEFAULT_ASSUMPTIONS } from "../../lib/engine";
import { RiskAssumptions } from "../../lib/types";
import generated from "../../data/generated.json";
import offlineReport from "../../data/validation-report.json";
import { fetchValidationReport } from "../../lib/api";
import { useTheme } from "../../lib/useTheme";

interface ValidationDetail {
  status: string;
  meaning: string;
}

interface ValidationScorecardItem {
  dimension: string;
  metric: string;
  result: string;
  status: string;
  details?: ValidationDetail[];
}

interface TornadoItem {
  param: string;
  label: string;
  low_mult: number;
  low_ale: number;
  high_mult: number;
  high_ale: number;
  swing: number;
}

interface ValidationReport {
  all_passed: boolean;
  missing?: boolean;
  scorecard: ValidationScorecardItem[];
  d5_decision_robustness?: {
    conclusion: string;
    tornado: TornadoItem[];
    one_at_a_time: { meaning: string };
  };
  limitations?: string[];
  d4_correctness_reproducibility?: {
    monte_carlo_agreement?: {
      status: string;
      tolerance_pct: number;
      rows: { percentile: string; python: number; typescript: number; relative_difference_pct: number }[];
    };
  };
}

// Copy of the last validation run, generated by scripts/sync-data.mjs from validation_report.json.
const OFFLINE_REPORT = offlineReport as unknown as ValidationReport;

function StatusBadge({ status }: { status: string }) {
  const pass = status === "PASS";
  return (
    <span
      className={`${pass ? "bg-[var(--stop-soft)] text-[var(--stop)]" : "bg-[var(--miss-soft)] text-[var(--miss)]"} text-xs font-semibold px-2.5 py-1 rounded-full inline-flex items-center gap-1`}
    >
      {pass ? <Check className="w-3.5 h-3.5" /> : <X className="w-3.5 h-3.5" />}
      <span>{status}</span>
    </span>
  );
}

export default function ValidationPage() {
  const { isDark, toggleTheme } = useTheme();
  const [isDrawerOpen, setIsDrawerOpen] = useState(false);
  const [assumptions, setAssumptions] = useState<RiskAssumptions>(DEFAULT_ASSUMPTIONS);
  const [report, setReport] = useState<ValidationReport>(OFFLINE_REPORT);
  const [isOffline, setIsOffline] = useState<boolean>(false);

  useEffect(() => {
    let cancelled = false;
    fetchValidationReport<ValidationReport>(OFFLINE_REPORT).then(({ data, isOffline }) => {
      if (!cancelled) {
        setReport(data);
        setIsOffline(isOffline);
      }
    });
    return () => {
      cancelled = true;
    };
  }, []);

  const scorecard = report.scorecard || [];
  const tornado = report.d5_decision_robustness?.tornado || [];



  const maxSwing = Math.max(...tornado.map((t) => t.swing), 1);

  return (
    <div className="min-h-screen flex flex-col bg-[var(--paper)] text-[var(--ink)]">
      <Header
        currentChapter={0}
        visitedChapters={new Set()}
        onSelectChapter={() => {}}
        onOpenAssumptions={() => setIsDrawerOpen(true)}
        isDark={isDark}
        onToggleTheme={toggleTheme}
      />

      <main className="flex-1 py-8">
        <div className="wrap max-w-[1320px] mx-auto px-6">
          <Link
            href="/"
            className="inline-flex items-center gap-1.5 text-sm font-semibold text-[var(--accent)] hover:underline mb-5"
          >
            <ArrowLeft className="w-4 h-4" />
            <span>Back to ROI Cyber-Validator</span>
          </Link>

          <h1 className="text-[34px] font-bold tracking-tight mb-3 text-[var(--ink)]">
            How we checked our data
          </h1>

          <p className="text-[18px] text-[var(--muted)] mb-8 leading-relaxed max-w-[85ch]">
            This project has no historical incident data for the fictional company, so{" "}
            <em>predictive</em> accuracy cannot be measured. Following data-quality best practice
            (dimensions used by ISO/IEC 25012 and DAMA-DMBOK), we measure (1) how faithfully our data
            reproduces its official sources, (2) completeness, validity and consistency, (3)
            traceability of every number, (4) correctness and reproducibility of the calculation engine,
            and (5) how stable the recommendations are when assumptions change.
          </p>

          {/* Section: Scorecard */}
          <div className="mb-10">
            <h2 className="text-[20px] font-bold text-[var(--ink)] mb-1">
              Validation Scorecard
            </h2>
            <p className="text-[14px] text-[var(--muted)] mb-4">
              Every result and status below is computed by <code>scripts/validate.py</code>
              {isOffline ? " (showing the copy from the last validation run — backend offline)" : " (last validation run)"}.
              {" "}Overall: <strong className="text-[var(--ink)]">{report.missing ? "not run yet" : report.all_passed ? "every check passed" : "at least one check failed"}</strong>.
            </p>
            <div className="rows flex flex-col gap-2.5">
              {scorecard.map((item, idx) => (
                <div
                  key={idx}
                  className="rrow bg-[var(--surface)] border border-[var(--line)] rounded-[10px] p-4 sm:px-5 sm:py-4 flex flex-col md:flex-row md:items-center justify-between gap-4 transition-colors"
                >
                  <div className="max-w-[70ch]">
                    <div className="font-semibold text-[17px] text-[var(--ink)] flex items-center gap-2 flex-wrap">
                      <span>{item.dimension}</span>
                      <span className="text-xs text-[var(--muted)] font-normal">
                        ({item.metric})
                      </span>
                    </div>
                    <ul className="text-[14.5px] text-[var(--muted)] mt-1 leading-normal space-y-1">
                      {(item.details || []).map((d, i) => (
                        <li key={i}>
                          {d.status === "PASS" || d.status === "INFO" ? "" : `[${d.status}] `}
                          {d.meaning}
                        </li>
                      ))}
                    </ul>
                  </div>

                  <div className="flex items-center gap-3.5 self-start md:self-center shrink-0">
                    <span className="font-bold text-lg sm:text-xl tabular-nums text-[var(--ink)]">
                      {item.result}
                    </span>
                    <StatusBadge status={item.status} />
                  </div>
                </div>
              ))}
            </div>
          </div>

          {/* Section: Monte Carlo range tolerance */}
          {report.d4_correctness_reproducibility?.monte_carlo_agreement && (
            <div className="card bg-[var(--surface)] border border-[var(--line)] rounded-[14px] p-6 mb-10">
              <h2 className="text-[20px] font-bold text-[var(--ink)] mb-1 flex items-center gap-3">
                <span>Loss ranges: browser vs server</span>
                <StatusBadge status={report.d4_correctness_reproducibility.monte_carlo_agreement.status} />
              </h2>
              <p className="text-[14.5px] text-[var(--muted)] leading-relaxed mb-3">
                The browser (TypeScript) and the server (Python) use different random number generators, so their
                P10–P90 ranges are not identical. We require them to agree within{" "}
                <strong className="text-[var(--ink)]">
                  ±{report.d4_correctness_reproducibility.monte_carlo_agreement.tolerance_pct}%
                </strong>
                . The most likely values (the headline numbers) are identical in both.
              </p>
              <ul className="text-[14px] text-[var(--muted)] space-y-1 tabular-nums">
                {report.d4_correctness_reproducibility.monte_carlo_agreement.rows.map((r) => (
                  <li key={r.percentile}>
                    {r.percentile.toUpperCase()}: server ${r.python.toLocaleString("en-US")} · browser $
                    {r.typescript.toLocaleString("en-US")} ({r.relative_difference_pct.toFixed(2)}% apart)
                  </li>
                ))}
              </ul>
            </div>
          )}

          {/* Section: Sensitivity Analysis (Tornado Table) */}
          <div className="card bg-[var(--surface)] border border-[var(--line)] rounded-[14px] p-6 mb-10">
            <div className="mb-5">
              <h2 className="text-[20px] font-bold text-[var(--ink)] mb-1">
                Decision Robustness — Sensitivity Analysis (Tornado Chart)
              </h2>
              <p className="text-[14.5px] text-[var(--muted)] leading-relaxed">
                Inputs ranked by impact on baseline total loss exposure. {report.d5_decision_robustness?.one_at_a_time.meaning}{" "}
                <strong className="text-[var(--ink)] font-semibold">{report.d5_decision_robustness?.conclusion}</strong>
              </p>
            </div>

            <div className="space-y-3">
              {tornado.map((item, idx) => {
                const pctOfMax = Math.max(2, (item.swing / maxSwing) * 100);
                return (
                  <div
                    key={idx}
                    className="grid grid-cols-1 lg:grid-cols-[280px_1fr_130px] gap-2 lg:gap-4 items-center text-[13.5px] py-1 border-b border-[var(--line)] last:border-b-0"
                  >
                    <div>
                      <div className="font-semibold text-[var(--ink)]">{item.label}</div>
                      <div className="text-xs font-mono text-[var(--muted)]">`{item.param}`</div>
                    </div>

                    <div className="flex items-center gap-2">
                      <span className="text-xs text-[var(--muted)] w-14 text-right tabular-nums">
                        ${Math.round(item.low_ale).toLocaleString()}
                      </span>
                      <div className="track flex-1 h-3 bg-[var(--soft)] rounded-full overflow-hidden">
                        <div
                          className="fill h-full rounded-full bg-[var(--stop)] transition-all duration-500"
                          style={{ width: `${pctOfMax}%` }}
                        />
                      </div>
                      <span className="text-xs text-[var(--muted)] w-14 tabular-nums">
                        ${Math.round(item.high_ale).toLocaleString()}
                      </span>
                    </div>

                    <div className="text-left lg:text-right font-bold text-[14px] tabular-nums text-[var(--ink)]">
                      ${Math.round(item.swing).toLocaleString()} swing
                    </div>
                  </div>
                );
              })}
            </div>
          </div>

          {/* Section: Validation limitations (from the report) */}
          {(report.limitations || []).length > 0 && (
            <div className="card bg-[var(--surface)] border border-[var(--line)] rounded-[14px] p-6 mb-6">
              <h2 className="text-[20px] font-bold text-[var(--ink)] mb-3 flex items-center gap-2">
                <AlertCircle className="w-5 h-5 text-[var(--muted)]" />
                <span>Validation Limitations</span>
              </h2>
              <ul className="list-disc pl-5 space-y-2 text-[15px] text-[var(--muted)] leading-relaxed">
                {(report.limitations || []).map((lim, idx) => (
                  <li key={idx}>{lim}</li>
                ))}
              </ul>
            </div>
          )}

          {/* Section: Model limitations */}
          <div className="card bg-[var(--surface)] border border-[var(--line)] rounded-[14px] p-6 mb-8">
            <h2 className="text-[20px] font-bold text-[var(--ink)] mb-3 flex items-center gap-2">
              <AlertCircle className="w-5 h-5 text-[var(--muted)]" />
              <span>Model Limitations</span>
            </h2>
            <ul className="list-disc pl-5 space-y-2 text-[15px] text-[var(--muted)] leading-relaxed">
              {((generated as { limitations?: { title: string; description: string }[] }).limitations || []).map((lim, idx) => (
                <li key={idx}>
                  <strong>{lim.title}:</strong> {lim.description}
                </li>
              ))}
            </ul>
          </div>
        </div>
      </main>

      <Footer />

      <AssumptionsDrawer
        isOpen={isDrawerOpen}
        onClose={() => setIsDrawerOpen(false)}
        assumptions={assumptions}
        onUpdateAssumptions={setAssumptions}
        onResetAssumptions={() => setAssumptions(DEFAULT_ASSUMPTIONS)}
      />
    </div>
  );
}
